// Turning a Google identity into a user row
// ---------------------------------------------------------------------------

/**
 * Finds or creates the student behind a set of Google claims.
 *
 * The matching rules, in order, and each one is a decision rather than a
 * detail:
 *
 *   1. A row in social_accounts for (google, sub) — the only identifier Google
 *      promises is stable. An email address is not: people change theirs, and
 *      the address alone would then either lock them out or, worse, hand their
 *      account to whoever inherits the address.
 *
 *   2. Failing that, a users row with the same email, ONLY when both sides say
 *      that email is verified. This is what lets a student the office already
 *      recorded sign in without becoming a second person in the database.
 *
 *   3. Failing that, a new student row.
 *
 * Staff and admin accounts are refused at step 2 and never reached at step 1,
 * because step 1 can only match a link this function refused to create. See the
 * header for why.
 *
 * @return array{0:?int,1:?string} [user id, error message for the visitor]
 */
function mpc_google_link_user(array $claims): array
{
    $db = mpc_db();

    $stmt = $db->prepare(
        "SELECT u.id, u.role, u.status
           FROM social_accounts s
           JOIN users u ON u.id = s.user_id
          WHERE s.provider = 'google' AND s.provider_user_id = ?"
    );
    $stmt->execute([$claims['sub']]);
    $linked = $stmt->fetch();

    if ($linked) {
        if ($linked['status'] !== 'active') {
            return [null, 'That account is suspended. Please call the office.'];
        }
        if (in_array($linked['role'], ['staff', 'admin'], true)) {
            return [null, mpc_google_staff_message()];
        }

        return [(int) $linked['id'], null];
    }

    $email    = $claims['email'];
    $verified = $claims['email_verified'];

    if ($email !== null && $verified) {
        $stmt = $db->prepare(
            "SELECT id, role, status, email_verified_at FROM users WHERE email = ?"
        );
        $stmt->execute([$email]);
        $existing = $stmt->fetch();

        if ($existing) {
            if (in_array($existing['role'], ['staff', 'admin'], true)) {
                return [null, mpc_google_staff_message()];
            }
            if ($existing['status'] !== 'active') {
                return [null, 'That account is suspended. Please call the office.'];
            }

            // An unverified existing row is NOT linked automatically. It was
            // created by someone typing an address — at the enrolment desk, or
            // into a form — and nobody has proved they own it. Linking here
            // would let anyone who can register that address at Google walk
            // into the account it names. It needs a human at the office to
            // confirm, and there is no screen for that yet, so it is refused
            // rather than guessed.
            if ($existing['email_verified_at'] === null) {
                return [null,
                    'An account already uses that email address, but it has not been '
                    . 'confirmed yet. Please call the office on +252 770 51 90 98 and '
                    . 'we will connect it for you.'];
            }

            mpc_google_insert_link((int) $existing['id'], $claims);

            return [(int) $existing['id'], null];
        }
    }

    // A brand new student. Role and status are written explicitly rather than
    // left to the column defaults, so that a change to those defaults later
    // cannot quietly start creating something other than an active student
    // from a public, unauthenticated endpoint.
    $insert = $db->prepare(
        "INSERT INTO users (full_name, email, email_verified_at, role, status, avatar_url)
         VALUES (?, ?, ?, 'student', 'active', ?)"
    );
    $insert->execute([
        mb_substr(trim($claims['name'] ?? '') ?: ($email ?? 'Student'), 0, 160),

        // Only store the address when Google vouches for it. An unverified one
        // would take the UNIQUE slot on users.email and block the real owner
        // from ever registering it.
        $verified ? $email : null,
        $verified ? date('Y-m-d H:i:s') : null,
        $claims['picture'] !== null ? mb_substr($claims['picture'], 0, 500) : null,
    ]);

    $userId = (int) $db->lastInsertId();
    mpc_google_insert_link($userId, $claims);

    return [$userId, null];
}

/** Records the provider link. Separate function because it happens from two
 *  places above and both must write the same row. */
function mpc_google_insert_link(int $userId, array $claims): void
{
    $stmt = mpc_db()->prepare(
        "INSERT INTO social_accounts
                (user_id, provider, provider_user_id, provider_email, email_verified)
         VALUES (?, 'google', ?, ?, ?)"
    );
    $stmt->execute([
        $userId,
        $claims['sub'],
        $claims['email'] !== null ? mb_substr($claims['email'], 0, 190) : null,
        $claims['email_verified'] ? 1 : 0,
    ]);
}

/** The one message staff see, in one place, so the two call sites cannot drift
 *  into saying different things about the same rule. */
function mpc_google_staff_message(): string
{
    return 'That address belongs to an MPC staff account. Staff sign in with a '
         . 'password at the office system, not with Google.';
}
